function CyberV.RollChanceBenefitsBasedOnLifePath(maxChance)
  local vPath = GameUtils.GetLifePath(Game.GetPlayer())
  if vPath == 'Corporate' then
    if CyberV.cyberNPC.IsRich() or
    CyberV.cyberNPC.IsCorpo()
    then
      return math.random(maxChance/3)
    end
  elseif vPath == "Nomad" then
    if CyberV.cyberNPC.IsNomad() or
    CyberV.cyberNPC.IsPunk or
    CyberV.cyberNPC.IsRedneck() or
    CyberV.cyberNPC.IsPunk()
    then
      return math.random(maxChance/3)
    end
  elseif vPath == "StreetKid" then
    if CyberV.cyberNPC.IsLatino() or
    CyberV.cyberNPC.IsLowlife() or
    CyberV.cyberNPC.IsHomeless() or
    CyberV.cyberNPC.IsSlacker()
    then
      return math.random(maxChance/3)
    end
  end
  return 0
end

