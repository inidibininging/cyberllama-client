function CyberV.GetPlayerInfoForServer()
    local player = Game.GetPlayer()
    if not player then
        return {
          error = 'no player found'
        }
    end
---@diagnostic disable-next-line: undefined-field
    local weatherState = Game.GetWeatherSystem():GetWeatherState()
    local weatherName = ''
    if weatherState and weatherState.name and weatherState.name.value then
        weatherName = tostring(weatherState.name.value):lower()
    end
    local quest = CyberV.gameUtils.GetActiveQuest()
    if CyberV.GetActiveQuest then
      local activeModQuest = CyberV.GetActiveQuest()
      if activeModQuest then
        quest = activeModQuest
      end
    end

    return {
        session = CyberV.gameSession.GetKey(),
        p_time = GetGameTime(),
        p_gender = CyberV.gameUtils.GetGender(player),
        p_health_armor =  CyberV.gameUtils.GetHealthArmor(player),
        p_lifepath =  CyberV.gameUtils.GetLifePath(player),
        p_quest = quest,
        p_district =  CyberV.gameUtils.GetDistrict(),
        p_location = CyberV.GetPlayerPos(),
        p_combat = CyberV.gameSession.inCombat,
        p_stats = {
        food = CyberV.cyberNPC.LLamaNPCFood,
        hydration = CyberV.cyberNPC.LLamaNPCHydration,
        fun = CyberV.cyberNPC.LLamaNPCFun,
        relationship = CyberV.cyberNPC.LLamaNPCRelationship
        },
        weather = {
        state = weatherName
        -- value = Game.GetWeatherSystem():GetWeatherState().value
        -- name = Game.GetWeatherSystem():GetWeatherState().name
        },
        in_interior = Game.IsEntityInInteriorArea(player),
        p_combat_state = {
        state = CyberV.cyberNPC.LastCombatState,
        time = CyberV.cyberNPC.LastCombatStateTime,
        last_combat = CyberV.cyberNPC.LastActualCombatTime,
        combat_duration = CyberV.cyberNPC.LastActualCombatDuration
        },
        p_last_action = CyberV.cyberNPC.LLamaNPCLastAction
        -- p_enemies = LastEnemiesCache
    }
end

