function CyberV.GetPlayerPos()
    local playerPos = Game.GetPlayer():GetWorldPosition()
    return {
        name = CyberV.locations.lastLocation,
        time = CyberV.locations.lastLocationTime,
        x = playerPos.x,
        y = playerPos.y,
        z = playerPos.z,
    }
end
