  local opposite = (angle + 180) % 360
  return CyberV.GetDirection(opposite)
end

-- all this borrowed from AMM
function CyberV.GetPosition(distance, angle)
  local pos = CyberV.GetWorldPostion()
  local heading = CyberV.GetDirection(angle)
  return Vector4.new(pos.x + (heading.x * distance), pos.y + (heading.y * distance), pos.z + heading.z, pos.w + heading.w)
end

function CyberV.GetWorldPostion()
  return Game.GetPlayer():GetWorldPosition()
end

